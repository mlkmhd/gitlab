<script>
import { GlAlert, GlBadge, GlButton, GlIcon, GlLink, GlPopover, GlSprintf } from '@gitlab/ui';
import { uniqueId } from 'lodash-es';
import { n__, s__, sprintf } from '~/locale';
import * as Sentry from '~/sentry/sentry_browser_wrapper';
import groupTriageAndRemediationFlowStatusesQuery from 'ee/security_configuration/graphql/scan_profiles/group_triage_and_remediation_flow_statuses.query.graphql';
import {
  SAST_FALSE_POSITIVE,
  SAST_VULNERABILITY_RESOLUTION,
  SBOM_INGESTED,
  SECRET_DETECTION_FALSE_POSITIVE,
  TRIAGE_CAPABILITY_STATUS_OFF_FOR_GROUP,
  TRIAGE_DEPENDENCY_SEVERITY_SCOPES,
  TRIAGE_PRESET_CAPABILITY_GROUPS,
  TRIAGE_RUN_MODE_LABELS,
  TRIAGE_SEVERITY_SCOPES,
  TRIAGE_UPGRADE_POLICIES,
} from 'ee/security_configuration/constants';
import { isOffForGroup } from './utils';

const CAPABILITY_DETAILS = {
  [SAST_FALSE_POSITIVE]: {
    description: s__(
      'ScanProfiles|Flags likely false positives, reviewing each SAST vulnerability.',
    ),
    note: s__('ScanProfiles|Analysis is performed by AI.'),
  },
  [SAST_VULNERABILITY_RESOLUTION]: {
    description: s__('ScanProfiles|Opens a fix merge request that rewrites vulnerable code.'),
    note: s__('ScanProfiles|Fixes are generated by AI.'),
  },
  [SBOM_INGESTED]: {
    description: s__(
      'ScanProfiles|Opens a fix merge request that updates the dependency to a safe version.',
    ),
    note: s__('ScanProfiles|Updates the dependency version without AI, so no credits are spent.'),
  },
  [SECRET_DETECTION_FALSE_POSITIVE]: {
    description: s__('ScanProfiles|Flags likely false positives, reviewing each detected secret.'),
    note: s__('ScanProfiles|Analysis is performed by AI.'),
  },
};

const UPGRADE_POLICY_HELP = s__(
  'ScanProfiles|Projects with Agentic Breaking Change Resolution turned on can also get major version upgrades.',
);

const capabilitySummary = (triggerType, configuration) => {
  if (!configuration) return null;

  if (triggerType === SBOM_INGESTED) {
    const { severityLevel, upgradePolicy, openMergeRequestsLimit } = configuration;

    return {
      text: [
        TRIAGE_DEPENDENCY_SEVERITY_SCOPES[severityLevel],
        TRIAGE_UPGRADE_POLICIES[upgradePolicy],
        n__(
          'ScanProfiles|Up to %d open MR',
          'ScanProfiles|Up to %d open MRs',
          openMergeRequestsLimit,
        ),
      ].join(' · '),
      helpText: upgradePolicy === 'MAJOR' ? '' : UPGRADE_POLICY_HELP,
    };
  }

  return {
    text: [
      TRIAGE_SEVERITY_SCOPES[configuration.severityLevel],
      TRIAGE_RUN_MODE_LABELS[configuration.runMode],
    ].join(' · '),
    helpText: '',
  };
};

const CAPABILITY_GROUPS = TRIAGE_PRESET_CAPABILITY_GROUPS.map((group) => ({
  ...group,
  capabilities: group.capabilities.map((capability) => ({
    ...capability,
    ...CAPABILITY_DETAILS[capability.triggerType],
  })),
}));

export default {
  name: 'TriagePresetCapabilities',
  components: {
    GlAlert,
    GlBadge,
    GlButton,
    GlIcon,
    GlLink,
    GlPopover,
    GlSprintf,
  },
  inject: {
    groupFullPath: { default: '' },
    rootGroupName: { default: '' },
    duoSettingsPath: { default: null },
    groupOwnersPath: { default: '' },
  },
  props: {
    triggers: {
      type: Array,
      required: true,
    },
    triggerSettings: {
      type: Array,
      required: false,
      default: () => [],
    },
  },
  data() {
    return {
      helpTargetIdPrefix: uniqueId('triage-preset-capability-help-'),
      flowStatuses: [],
    };
  },
  apollo: {
    flowStatuses: {
      query: groupTriageAndRemediationFlowStatusesQuery,
      skip() {
        return !this.groupFullPath;
      },
      variables() {
        return { fullPath: this.groupFullPath };
      },
      update(data) {
        return data?.group?.triageAndRemediationFlowStatuses ?? [];
      },
      error(error) {
        Sentry.captureException(error);
      },
    },
  },
  computed: {
    capabilityGroups() {
      return CAPABILITY_GROUPS.map((group) => ({
        ...group,
        capabilities: group.capabilities
          .filter(({ triggerType }) => this.triggers.includes(triggerType))
          .map((capability) => ({
            ...capability,
            isOffForGroup: isOffForGroup(
              this.flowStatuses.find(({ triggerType }) => triggerType === capability.triggerType),
            ),
            summary: capabilitySummary(
              capability.triggerType,
              this.triggerSettings.find(({ triggerType }) => triggerType === capability.triggerType)
                ?.configuration,
            ),
          })),
      })).filter((group) => group.capabilities.length);
    },
    offCapabilities() {
      return this.capabilityGroups
        .flatMap(({ capabilities }) => capabilities)
        .filter((capability) => capability.isOffForGroup);
    },
  },
  methods: {
    helpTargetId({ triggerType }) {
      return `${this.helpTargetIdPrefix}-${triggerType}`;
    },
    offForGroupBadgeId({ triggerType }) {
      return `${this.helpTargetIdPrefix}-off-for-group-${triggerType}`;
    },
    helpLabel({ title }) {
      return sprintf(s__('ScanProfiles|About %{capability}'), { capability: title });
    },
  },
  TRIAGE_CAPABILITY_STATUS_OFF_FOR_GROUP,
};
</script>

<template>
  <div class="gl-flex gl-flex-col gl-gap-5">
    <gl-alert
      v-if="offCapabilities.length"
      variant="info"
      :title="s__(`ScanProfiles|Some capabilities won't run yet`)"
      :dismissible="false"
      data-testid="off-for-group-alert"
    >
      <ul class="gl-m-0 gl-pl-5">
        <li
          v-for="capability in offCapabilities"
          :key="capability.triggerType"
          data-testid="off-for-group-capability"
        >
          <gl-sprintf
            v-if="duoSettingsPath"
            :message="
              s__(
                'ScanProfiles|%{capability} is off for %{groupName}. Turn it on in %{linkStart}GitLab Duo settings%{linkEnd}.',
              )
            "
          >
            <template #capability>
              <strong>{{ capability.title }}</strong>
            </template>
            <template #groupName>{{ rootGroupName }}</template>
            <template #link="{ content }">
              <gl-link :href="duoSettingsPath" data-testid="duo-settings-link">{{
                content
              }}</gl-link>
            </template>
          </gl-sprintf>
          <gl-sprintf
            v-else
            :message="
              s__(
                'ScanProfiles|%{capability} is off for %{groupName}. Ask a %{linkStart}group Owner%{linkEnd} to turn this on.',
              )
            "
          >
            <template #capability>
              <strong>{{ capability.title }}</strong>
            </template>
            <template #groupName>{{ rootGroupName }}</template>
            <template #link="{ content }">
              <gl-link :href="groupOwnersPath" data-testid="group-owners-link">{{
                content
              }}</gl-link>
            </template>
          </gl-sprintf>
        </li>
      </ul>
    </gl-alert>
    <section v-for="group in capabilityGroups" :key="group.title">
      <h4 class="gl-heading-4 gl-mb-3">{{ group.title }}</h4>
      <ul class="gl-m-0 gl-flex gl-list-none gl-flex-col gl-gap-3 gl-p-0">
        <li
          v-for="capability in group.capabilities"
          :key="capability.triggerType"
          class="gl-flex gl-items-center gl-gap-3 gl-rounded-xl gl-bg-strong gl-px-5 gl-py-4"
          :data-testid="`capability-${capability.triggerType}`"
        >
          <gl-icon :name="capability.icon" :size="16" class="gl-shrink-0" />
          <div class="gl-flex gl-grow gl-flex-col gl-gap-1">
            <div class="gl-flex gl-items-center gl-gap-2">
              <h5 class="gl-heading-5 gl-mb-0">{{ capability.title }}</h5>
              <gl-button
                :id="helpTargetId(capability)"
                category="tertiary"
                size="small"
                icon="information-o"
                :aria-label="helpLabel(capability)"
              />
              <gl-popover :target="helpTargetId(capability)">
                <p class="gl-mb-0">{{ capability.description }}</p>
                <p class="gl-mb-0 gl-mt-2 gl-text-sm gl-text-subtle">{{ capability.note }}</p>
              </gl-popover>
            </div>
            <template v-if="capability.summary">
              <p class="gl-mb-0 gl-text-subtle" data-testid="capability-summary">
                {{ capability.summary.text }}
              </p>
              <p
                v-if="capability.summary.helpText"
                class="gl-mb-0 gl-text-sm gl-text-subtle"
                data-testid="capability-help"
              >
                {{ capability.summary.helpText }}
              </p>
            </template>
          </div>
          <template v-if="capability.isOffForGroup">
            <gl-badge
              :id="offForGroupBadgeId(capability)"
              tag="button"
              type="button"
              :variant="$options.TRIAGE_CAPABILITY_STATUS_OFF_FOR_GROUP.variant"
              :icon="$options.TRIAGE_CAPABILITY_STATUS_OFF_FOR_GROUP.icon"
              class="gl-border-0 focus-visible:gl-focus"
              data-testid="off-for-group-badge"
            >
              {{ $options.TRIAGE_CAPABILITY_STATUS_OFF_FOR_GROUP.label }}
            </gl-badge>
            <gl-popover
              :target="offForGroupBadgeId(capability)"
              placement="top"
              :title="$options.TRIAGE_CAPABILITY_STATUS_OFF_FOR_GROUP.label"
              data-testid="off-for-group-popover"
            >
              <gl-sprintf
                :message="
                  s__(
                    `ScanProfiles|On in this profile, but turned off for %{groupName}, so it won't run.`,
                  )
                "
              >
                <template #groupName>{{ rootGroupName }}</template>
              </gl-sprintf>
            </gl-popover>
          </template>
        </li>
      </ul>
    </section>
  </div>
</template>
